"""Create small runtime atlases from archived imagegen originals.
Run in project root after placing the nine RGBA originals in work/source-art/collection.
Only resizes/re-encodes: no palette reduction, alpha stripping or lossy compression.
"""
from pathlib import Path
import json
from collections import deque
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
IDS = ("cat", "dog", "dragon", "bling", "bee", "unicorn", "robot", "ghost", "chef")
source = ROOT / "work/source-art/collection"
target = ROOT / "assets/toon/collection"
target.mkdir(parents=True, exist_ok=True)
def part_bounds(image, cell_x, cell_y):
    # Find the largest solid island; ignore faint alpha noise and neighbouring-cell fragments.
    tile = image.crop((cell_x * 256, cell_y * 256, (cell_x + 1) * 256, (cell_y + 1) * 256))
    alpha = tile.getchannel("A")
    pixels = alpha.load()
    visited = bytearray(256 * 256)
    largest = []
    for y in range(256):
        for x in range(256):
            offset = y * 256 + x
            if visited[offset] or pixels[x, y] < 128:
                continue
            queue = deque([(x, y)])
            visited[offset] = 1
            component = []
            while queue:
                px, py = queue.popleft()
                component.append((px, py))
                for nx, ny in ((px - 1, py), (px + 1, py), (px, py - 1), (px, py + 1)):
                    if 0 <= nx < 256 and 0 <= ny < 256:
                        no = ny * 256 + nx
                        if not visited[no] and pixels[nx, ny] >= 128:
                            visited[no] = 1
                            queue.append((nx, ny))
            if len(component) > len(largest):
                largest = component
    assert largest, (cell_x, cell_y)
    x0 = max(0, min(x for x, y in largest) - 2)
    y0 = max(0, min(y for x, y in largest) - 2)
    x1 = min(256, max(x for x, y in largest) + 3)
    y1 = min(256, max(y for x, y in largest) + 3)
    return [cell_x * 256 + x0, cell_y * 256 + y0, x1 - x0, y1 - y0]

regions = {}
head_contacts = []
report = []
for character in IDS:
    src = source / (character + ".png")
    dst = target / (character + ".png")
    with Image.open(src) as original:
        assert original.mode == "RGBA", (character, original.mode)
        assert original.width == original.height, character
        image = original.resize((512, 512), Image.Resampling.LANCZOS)
        image.save(dst, optimize=True, compress_level=9)
        regions[character] = [part_bounds(image, x, y) for y in range(2) for x in range(2)]
        hx, hy, hw, hh = regions[character][1]
        head_alpha = image.getchannel("A").crop((hx, hy, hx + hw, hy + hh))
        # Anchor the underside at the centre of the headpiece to the gummy scalp.
        contact_rows = [y for y in range(hh) if any(head_alpha.getpixel((x, y)) >= 128 for x in range(int(hw * .45), int(hw * .55) + 1))]
        assert contact_rows, character
        head_contacts.append((max(contact_rows) + .5) / hh)
        alpha = image.getchannel("A")
        assert alpha.getextrema()[0] == 0 and alpha.getextrema()[1] == 255, character
        report.append({"id": character, "original_size": list(original.size), "original_bytes": src.stat().st_size, "runtime_size": [512, 512], "runtime_bytes": dst.stat().st_size})
        print(f"{character}: {src.stat().st_size:,} -> {dst.stat().st_size:,} bytes")
source_total = sum(row["original_bytes"] for row in report)
runtime_total = sum(row["runtime_bytes"] for row in report)
print(f"TOTAL: {source_total:,} -> {runtime_total:,} bytes ({100 * (1 - runtime_total / source_total):.1f}% smaller)")
(target / "sizes.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

(target / "atlas-regions.json").write_text(json.dumps(regions, indent=2) + "\n", encoding="utf-8")

(target / "atlas_regions.gd").write_text("extends RefCounted\n# Generated by work/prepare_collection.py. Coordinates refer to the 512px atlases.\nconst REGIONS = " + json.dumps(regions, indent=2) + "\nconst HEAD_CONTACT_RATIOS = " + json.dumps(head_contacts) + "\n", encoding="utf-8")
